# prep.py - trim and measure raising-chicago sprites; writes public/ PNGs + src/shorts/raising-chicago/sprites.ts
import json, os, sys
import cv2
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
REUSED_DOT = ["dot_lookup", "dot_surprised", "dot_aha", "dot_watch", "dot_shrug"]
OWN = ["building_a", "building_b", "worker_jack", "townsman", "townswoman"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))

trims = {}
for n in OWN:
    im, tr = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "raising-chicago", n + ".png"))
    trims[n] = tr
    a = np.array(im)[:, :, 3]
    ys, xs = np.where(a > 128)
    out[n] = {"src": f"raising-chicago/{n}.png", "w": im.width, "h": im.height, "bottom": float(ys.max())}


def to_trim(n, x, y):
    x0, y0, s = trims[n]
    return [round((x - x0) * s, 1), round((y - y0) * s, 1)]


# buildings: window glass boxes (light-blue components) in trimmed px, top to bottom, left to right; the big one at
# the bottom is the shop window
for n in ["building_a", "building_b"]:
    raw = np.array(Image.open(os.path.join(RAW, n + ".png")).convert("RGBA")).astype(int)
    a = raw[:, :, 3] > 128
    glass = a & (raw[:, :, 2] > 200) & (raw[:, :, 0] < 200) & (raw[:, :, 0] > 90)
    k, _, st, _ = cv2.connectedComponentsWithStats(glass.astype(np.uint8))
    boxes = sorted([st[i] for i in range(1, k) if st[i][4] > 30000], key=lambda s: (s[1] // 100, s[0]))
    shop = max(boxes, key=lambda s: s[2] * s[3])
    s = trims[n][2]
    box = lambda b: to_trim(n, b[0], b[1]) + [round(b[2] * s, 1), round(b[3] * s, 1)]
    out[n]["windows"] = [box(b) for b in boxes if b[1] + b[3] < shop[1]]
    out[n]["shop"] = box(shop)

# building_a: the dark green door (right of the shop window)
raw = np.array(Image.open(os.path.join(RAW, "building_a.png")).convert("RGBA")).astype(int)
r, g, b, al = raw[:, :, 0], raw[:, :, 1], raw[:, :, 2], raw[:, :, 3]
green = (al > 128) & (g > r + 15) & (g > b) & (g < 140)
green[: int(raw.shape[0] * 0.7)] = False  # only the ground floor
green[:, : int(raw.shape[1] * 0.55)] = False
k, lab, st, _ = cv2.connectedComponentsWithStats(green.astype(np.uint8))
d = max(range(1, k), key=lambda i: st[i][4])
x, y, w, h = st[d][:4]
s = trims["building_a"][2]
out["building_a"]["door"] = to_trim("building_a", x, y) + [round(w * s, 1), round(h * s, 1)]

# worker: the jack's top plate (highest opaque point in the left 40 %) - it touches the building's underside
a = np.array(Image.open(os.path.join(ROOT, "public", "raising-chicago", "worker_jack.png")))[:, :, 3] > 128
h, w = a.shape
left = a[:, : int(w * 0.4)]
ys, xs = np.where(left)
top = ys.min()
row = np.where(left[top + 4])[0]
out["worker_jack"]["plate"] = [float(row.mean()), float(top)]

# townsfolk: head disc (upper 60 % of the figure, below the hat / bonnet brim)
for n in ["townsman", "townswoman"]:
    a = np.array(Image.open(os.path.join(ROOT, "public", "raising-chicago", n + ".png")))[:, :, 3]
    reg = np.zeros_like(a, dtype=bool)
    reg[int(a.shape[0] * 0.2): int(a.shape[0] * 0.65)] = True
    out[n]["head"] = inscribed_disc(a, reg)

ts = "// generated by images/raising-chicago/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
os.makedirs(os.path.join(ROOT, "src", "shorts", "raising-chicago"), exist_ok=True)
open(os.path.join(ROOT, "src", "shorts", "raising-chicago", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk not in ("src", "windows")} for k, v in out.items()}, indent=0))
print("windows a", out["building_a"]["windows"][:2], len(out["building_a"]["windows"]), "b", len(out["building_b"]["windows"]))
