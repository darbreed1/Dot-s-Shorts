# prep.py - trim and measure pickaxe-mountain-fallout sprites; writes public/ PNGs + src/shorts/pickaxe-mountain-fallout/sprites.ts
import json, os, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
REUSED_DOT = ["dot_lookup", "dot_surprised", "dot_shrug", "dot_magnify", "dot_aha", "dot_scratch"]
OWN = ["mountain", "bomb", "cylinder"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))
# override measured in earlier episodes: the lens overlaps dot_magnify's head
out["dot_magnify"]["head"] = [396, 711, 287.0]

for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "pickaxe-mountain-fallout", n + ".png"))
    out[n] = {"src": f"pickaxe-mountain-fallout/{n}.png", "w": im.width, "h": im.height}

# mountain: the peak (topmost opaque point) and the two tunnel mouths (dark pixels in the bottom 15 %, split left/right)
px = np.array(Image.open(os.path.join(ROOT, "public", "pickaxe-mountain-fallout", "mountain.png")).convert("RGBA")).astype(int)
a = px[:, :, 3] > 128
h, w = a.shape
ys, xs = np.where(a)
out["mountain"]["peak"] = [float(xs[ys.argmin()]), float(ys.min())]
dark = a & (px[:, :, :3].sum(2) < 120)
dark[: int(h * 0.85)] = False
dark[int(h * 0.97):] = False
ys, xs = np.where(dark)
tun = []
for side in (xs < w / 2, xs >= w / 2):
    tun.append([float(xs[side].mean()), float(ys[side].mean())])
out["mountain"]["tunnels"] = tun
# cylinder: the valve (topmost opaque point)
a = np.array(Image.open(os.path.join(ROOT, "public", "pickaxe-mountain-fallout", "cylinder.png")))[:, :, 3] > 128
ys, xs = np.where(a)
out["cylinder"]["valve"] = [float(xs[ys.argmin()]), float(ys.min())]

ts = "// generated by images/pickaxe-mountain-fallout/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "shorts", "pickaxe-mountain-fallout", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk not in ("src", "ball")} for k, v in out.items()}))
