# prep.py - trim and measure crocodiles-survived sprites; writes public/ PNGs + src/shorts/crocodiles-survived/sprites.ts
import json, os, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
REUSED_DOT = ["dot_lookup", "dot_scared", "dot_magnify", "dot_watch", "dot_aha", "dot_shrug"]
OWN = ["croc", "dino"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))
# overrides measured in earlier episodes: the lens overlaps dot_magnify's head; the hands merge into dot_scared's
out["dot_magnify"]["head"] = [396, 711, 287.0]
out["dot_scared"]["head"] = [406, 779, 288.0]

for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "crocodiles-survived", n + ".png"))
    a = np.array(im)[:, :, 3]
    out[n] = {"src": f"crocodiles-survived/{n}.png", "w": im.width, "h": im.height, "feet": feet(a)}

# croc: the eye bumps on top of the head (topmost opaque point in the left 35 %) and the snout tip (leftmost point),
# so the waterline can sit just under the eyes
a = np.array(Image.open(os.path.join(ROOT, "public", "crocodiles-survived", "croc.png")))[:, :, 3] > 128
h, w = a.shape
ys, xs = np.where(a[:, : int(w * 0.35)])
out["croc"]["eyes"] = [float(xs[ys.argmin()]), float(ys.min())]
ys, xs = np.where(a)
out["croc"]["snout"] = [float(xs.min()), float(ys[xs.argmin()])]

ts = "// generated by images/crocodiles-survived/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "shorts", "crocodiles-survived", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk not in ("src", "ball")} for k, v in out.items() if k in OWN}))
