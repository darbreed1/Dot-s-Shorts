# prep.py - trim and measure airplane-window-hole sprites; writes public/ PNGs + src/shorts/airplane-window-hole/sprites.ts
import json, os, shutil, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
NEW_DOT = ["dot_three"]
REUSED_DOT = ["dot_magnify", "dot_aha", "dot_shrug", "dot_lookup"]
OWN = ["airliner", "seat"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in NEW_DOT:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dot", n + ".png"))
    out[n] = dot_entry(n, im)
    shutil.copy(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "images", "dot", n + ".png"))
for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))
out["dot_magnify"]["head"] = [396, 711, 287.0]  # the lens overlaps the head (dwarf-planet-ed138/qa/measure.png)
out["dot_magnify"]["lens"] = [639, 666, 160.0]

for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "airplane-window-hole", n + ".png"))
    out[n] = {"src": f"airplane-window-hole/{n}.png", "w": im.width, "h": im.height}
    a = np.array(im)[:, :, 3]
    ys, xs = np.where(a > 128)
    out[n]["bottom"] = float(ys.max())

# seat: the cushion top = the highest opaque row inside the cushion's x-range (left 55 % of the seat, below the
# armrest), where Dot stands
s = np.array(Image.open(os.path.join(ROOT, "public", "airplane-window-hole", "seat.png")))
a = s[:, :, 3] > 128
h, w = a.shape
band = a[int(h * 0.55):, : int(w * 0.35)]
rows = np.where(band.sum(1) > band.shape[1] * 0.6)[0]
out["seat"]["cushion"] = [float(w * 0.2), float(int(h * 0.55) + rows.min())]

ts = "// generated by images/airplane-window-hole/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "shorts", "airplane-window-hole", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "src"} for k, v in out.items()}))
