# prep.py - trim and measure the falling long-form sprites; writes public/ PNGs + src/longform/falling/sprites.ts
import json, os, shutil, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
NEW_DOT = ["dot_freefall", "dot_headdown", "dot_canopy"]  # flying poses: placed by their centre
REUSED_DOT = ["dot_lookup", "dot_aha", "dot_shrug", "dot_surprised", "dot_scratch", "dot_watch"]
OWN = ["plane", "station"]

out = {}


def centre(a):
    ys, xs = np.where(a > 128)
    return [float((xs.min() + xs.max()) / 2), float((ys.min() + ys.max()) / 2)]


for n in NEW_DOT:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dot", n + ".png"))
    a = np.array(im)[:, :, 3]
    out[n] = {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "centre": centre(a)}
    shutil.copy(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "images", "dot", n + ".png"))
for n in REUSED_DOT:
    im = Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA")
    px = np.array(im)
    out[n] = {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px),
              "centre": centre(px[:, :, 3])}

for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "falling", n + ".png"))
    out[n] = {"src": f"falling/{n}.png", "w": im.width, "h": im.height, "centre": centre(np.array(im)[:, :, 3])}

ts = "// generated by images/falling/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "longform", "falling", "sprites.ts"), "w").write(ts)
print(json.dumps({k: [v["w"], v["h"]] for k, v in out.items()}))
