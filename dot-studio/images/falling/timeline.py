# timeline.py - lay the 6 voice sections end to end (START, then GAP between sections), map every script word onto
# its voice time (images/lib/captions.py per section), and write src/longform/falling/timeline.ts +
# out/falling-longform.srt. Run images/falling/clean.py first.
import json, os, subprocess, sys, wave

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
START, GAP, TAIL = 0.6, 1.2, 1.8
TITLES = ["Everything falls", "How fast do you fall?", "The record that might not be true",
          "How a parachute works", "Why the space station is falling", "Everything is falling"]

secs, words, srt, at = [], [], [], START
tmp = os.path.join(HERE, "tmp")
os.makedirs(tmp, exist_ok=True)
for i in range(1, 7):
    n = f"{i:02d}"
    with wave.open(os.path.join(ROOT, "public", "falling", "vo", f"s{n}.wav")) as f:
        dur = f.getnframes() / f.getframerate()
    subprocess.run([sys.executable, os.path.join(ROOT, "images", "lib", "captions.py"), os.path.join(HERE, "script", f"s{n}.txt"),
                    os.path.join(HERE, "words", f"s{n}.json"), str(at), os.path.join(tmp, f"s{n}.ts"), os.path.join(tmp, f"s{n}.srt")],
                   check=True, capture_output=True)
    src = open(os.path.join(tmp, f"s{n}.ts"), encoding="utf-8").read()
    words += json.loads(src[src.index("["):src.rindex("]") + 1])
    srt.append(open(os.path.join(tmp, f"s{n}.srt"), encoding="utf-8").read().strip())
    secs.append({"n": i, "at": round(at, 3), "dur": round(dur, 3), "title": TITLES[i - 1]})
    at += dur + GAP
end = round(secs[-1]["at"] + secs[-1]["dur"] + TAIL, 2)

cues, k = [], 1
for block in "\n\n".join(srt).split("\n\n"):
    lines = block.strip().split("\n")
    if len(lines) >= 3:
        cues.append("\n".join([str(k)] + lines[1:]))
        k += 1
open(os.path.join(ROOT, "out", "falling-longform.srt"), "w", encoding="utf-8").write("\n\n".join(cues) + "\n")
ts = "// generated by images/falling/timeline.py - do not edit\n"
ts += "export const SECTIONS = " + json.dumps(secs, indent=1) + " as const;\n"
ts += f"export const END = {end};\n"
ts += "export const WORDS = " + json.dumps(words, ensure_ascii=False) + " as const;\n"
os.makedirs(os.path.join(ROOT, "src", "longform", "falling"), exist_ok=True)
open(os.path.join(ROOT, "src", "longform", "falling", "timeline.ts"), "w", encoding="utf-8").write(ts)
for s in secs:
    m, sec = divmod(int(s["at"]), 60)
    print(f'{m}:{sec:02d}  s{s["n"]:02d} {s["title"]:36s} dur {s["dur"]:.2f}')
print("end", end, f"= {int(end // 60)}:{int(end % 60):02d}", len(words), "words", k - 1, "cues")
