# prep.py - trim and measure doomsday-november-13 sprites; writes public/ PNGs + src/shorts/doomsday-november-13/sprites.ts
import json, os, shutil, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
NEW_DOT = ["dot_scared"]
REUSED_DOT = ["dot_watch", "dot_lookup", "dot_surprised", "dot_aha", "dot_shrug"]
OWN = ["black_cat"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in NEW_DOT:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dot", n + ".png"))
    out[n] = dot_entry(n, im)
    shutil.copy(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "images", "dot", n + ".png"))
for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))

# dot_scared: the hands gripping the hat brim merge into the head disc (r 332); ball-to-feet height equals the other
# poses' (1741 px), so use their head radius
out["dot_scared"]["head"] = [406, 779, 288.0]

for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "doomsday-november-13", n + ".png"))
    a = np.array(im)[:, :, 3]
    out[n] = {"src": f"doomsday-november-13/{n}.png", "w": im.width, "h": im.height, "feet": feet(a)}

ts = "// generated by images/doomsday-november-13/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "shorts", "doomsday-november-13", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "src"} for k, v in out.items()}))
