# prep.py - trim and measure the computer long-form sprites; writes public/ PNGs + src/longform/computer/sprites.ts
import json, os, shutil, sys
import cv2
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import feet, inscribed_disc, largest_component, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
NEW_DOT = ["dot_snip", "dot_warm"]
REUSED_DOT = ["dot_lookup", "dot_aha", "dot_shrug", "dot_scratch", "dot_two", "dot_three", "dot_surprised", "dot_droop", "dot_watch", "dot_magnify"]
OWN = ["chip", "laptop", "cooler", "ram_stick", "speaker"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in NEW_DOT:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dot", n + ".png"))
    out[n] = dot_entry(n, im)
    shutil.copy(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "images", "dot", n + ".png"))
for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))
out["dot_magnify"]["head"] = [396, 711, 287.0]  # the lens overlaps the head (dwarf-planet-ed138/qa/measure.png)

ims = {}
for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "computer", n + ".png"))
    ims[n] = np.array(im)
    a = ims[n][:, :, 3] > 128
    ys, xs = np.where(a)
    out[n] = {"src": f"computer/{n}.png", "w": im.width, "h": im.height, "centre": [float(xs.mean()), float(ys.mean())],
              "bottom": float(ys.max())}

# chip: the lid came out with a blurry smudge; flatten the light-grey lid to one flat silver with a soft shade band
c = ims["chip"].copy()
hsv = cv2.cvtColor(c[:, :, :3], cv2.COLOR_RGB2HSV).astype(int)
lid = largest_component(((hsv[:, :, 1] < 40) & (hsv[:, :, 2] > 110) & (c[:, :, 3] > 200)) | ((hsv[:, :, 0] > 40) & (hsv[:, :, 0] < 90) & (hsv[:, :, 2] > 110) & (hsv[:, :, 1] < 120) & (c[:, :, 3] > 200) & False))
lid = cv2.morphologyEx(lid.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((25, 25), np.uint8)).astype(bool)
hull = np.zeros(lid.shape, np.uint8)
cv2.fillPoly(hull, [cv2.convexHull(np.argwhere(lid)[:, ::-1].astype(np.int32))], 1)  # the whole lid, smudge included
inner = cv2.erode(hull, np.ones((9, 9), np.uint8)).astype(bool)
ys, xs = np.where(inner)
c[inner, :3] = (206, 209, 214)
c[cv2.erode(hull, np.ones((3, 3), np.uint8)).astype(bool), 3] = 255  # the smudge was half transparent
band = inner & ((np.arange(c.shape[0])[:, None] - ys.min()) > (ys.max() - ys.min()) * 0.72)
c[band, :3] = (184, 188, 195)
Image.fromarray(c).save(os.path.join(ROOT, "public", "computer", "chip.png"), optimize=True)
out["chip"]["lid"] = [float(xs.mean()), float(ys.mean()), float((xs.max() - xs.min()) / 2), float((ys.max() - ys.min()) / 2)]

# laptop: the light-blue screen (box) to draw on
lp = ims["laptop"]
hsv = cv2.cvtColor(lp[:, :, :3], cv2.COLOR_RGB2HSV).astype(int)
scr = largest_component((hsv[:, :, 0] > 90) & (hsv[:, :, 0] < 110) & (hsv[:, :, 1] > 60) & (hsv[:, :, 2] > 180) & (lp[:, :, 3] > 200))
ys, xs = np.where(scr)
out["laptop"]["screen"] = [float(xs.min()), float(ys.min()), float(xs.max()), float(ys.max())]
# cooler fan and speaker cone centres read off qa/measure.png (the dark-pixel searches caught rings, not centres)
out["cooler"]["fan"] = [609.0, 658.0, 497.0]
out["speaker"]["cone"] = [574.0, 1102.0, 413.0]

ts = "// generated by images/computer/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "longform", "computer", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk not in ("src", "ball")} for k, v in out.items() if not k.startswith("dot_") or k in NEW_DOT}))
