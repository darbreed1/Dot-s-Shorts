# prep.py - trim and measure terracotta-fingerprints sprites; writes public/ PNGs + src/shorts/terracotta-fingerprints/sprites.ts
import json, os, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import blur_copy, feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
REUSED_DOT = ["dot_lookup", "dot_aha", "dot_watch", "dot_magnify", "dot_shrug"]  # trimmed in public/dot already
OWN = ["warrior", "worker_man", "worker_woman", "worker_child"]

out = {}
for n in REUSED_DOT:
    im = Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA")
    px = np.array(im)
    out[n] = {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}
# the magnifier lens overlaps the head (see images/dwarf-planet-ed138/qa/measure.png)
out["dot_magnify"]["head"] = [396, 711, 287.0]
out["dot_magnify"]["lens"] = [639, 666, 160.0]

ims = {}
for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "terracotta-fingerprints", n + ".png"))
    ims[n] = im
    a = np.array(im)[:, :, 3]
    # head = largest disc in the top 40 % (the robes / armour are wider lower down)
    region = np.zeros(a.shape, np.uint8)
    region[: int(a.shape[0] * 0.4)] = 1
    out[n] = {"src": f"terracotta-fingerprints/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(a, region), "feet": feet(a)}

# the warrior stands in rows behind Dot: a soft copy for the back rows (depth of field)
blur_copy(ims["warrior"], os.path.join(ROOT, "public", "terracotta-fingerprints", "warrior_blur.png"), 4.0)
out["warrior"]["blur"] = "terracotta-fingerprints/warrior_blur.png"

ts = "// generated by images/terracotta-fingerprints/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "shorts", "terracotta-fingerprints", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "src"} for k, v in out.items()}))
