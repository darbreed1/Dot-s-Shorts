# captions.py SCRIPT.txt WORDS.json VO_AT OUT.ts OUT.srt
# Script words (exact spelling) mapped one-to-one onto Whisper word times, starts snapped to loudness pauses
# (the first word after a pause starts when the pause ends - Whisper edges are +-0.2 s). Writes a TS table for the
# burned-in captions and an .srt (<= ~32 chars per line, 1-2 lines per cue, each cue >= 0.8 s).
import json, re, sys

script_path, words_path, vo_at, ts_path, srt_path = sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4], sys.argv[5]
script = open(script_path, encoding="utf-8-sig").read().split()
W = json.load(open(words_path))
words, pauses = W["words"], W["pauses"]
if len(script) != len(words):
    sys.exit(f"word count mismatch: script {len(script)} vs whisper {len(words)} - fix by hand")

starts = [w["s"] for w in words]
for p0, p1 in pauses:
    for i, s in enumerate(starts):
        if s >= p0 - 0.05:
            starts[i] = p1  # loudness says speech resumes exactly here
            break
for i in range(1, len(starts)):
    starts[i] = max(starts[i], starts[i - 1] + 0.08)
ends = []
for i, w in enumerate(words):
    nxt = starts[i + 1] if i + 1 < len(words) else w["e"] + 0.15
    ends.append(min(max(w["e"], starts[i] + 0.12), nxt))

out = [{"w": script[i], "s": round(starts[i] + vo_at, 3), "e": round(ends[i] + vo_at, 3)} for i in range(len(script))]
open(ts_path, "w", encoding="utf-8").write(
    "// generated by images/lib/captions.py - do not edit\n"
    "export const WORDS = " + json.dumps(out, indent=0) + " as const;\n")

# .srt: sentence-aware cues, <= 2 lines of <= 32 chars
cues, cur = [], []
def flush():
    if cur:
        cues.append(list(cur)); cur.clear()
for i, w in enumerate(out):
    cur.append(w)
    text = " ".join(x["w"] for x in cur)
    end_sentence = re.search(r"[.?!]$", w["w"]) is not None
    if end_sentence:
        flush()
    elif len(text) > 46:
        # don't leave a cue hanging on a little word ("that", "a", "the" ...): carry it into the next cue
        carry = cur.pop() if cur[-1]["w"].lower() in {"that", "a", "an", "the", "to", "and", "of", "so"} else None
        flush()
        if carry:
            cur.append(carry)
flush()

def fmt(t):
    ms = int(round(t * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"

def wrap(text, n=32):
    if len(text) <= n:
        return text
    words_ = text.split(); best = None
    for k in range(1, len(words_)):
        a, b = " ".join(words_[:k]), " ".join(words_[k:])
        score = max(len(a), len(b))
        if best is None or score < best[0]:
            best = (score, a + "\n" + b)
    return best[1]

lines = []
for i, c in enumerate(cues):
    s, e = c[0]["s"], c[-1]["e"]
    if i + 1 < len(cues):
        e = min(max(e, s + 0.8), cues[i + 1][0]["s"])
    else:
        e = max(e, s + 0.8)
    lines += [str(i + 1), f"{fmt(s)} --> {fmt(e)}", wrap(" ".join(x["w"] for x in c)), ""]
open(srt_path, "w", encoding="utf-8").write("\n".join(lines))
print(f"{len(out)} words, {len(cues)} cues")
