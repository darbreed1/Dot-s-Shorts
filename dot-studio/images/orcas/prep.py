# prep.py - trim and measure the orca long-form sprites; writes public/ PNGs + src/longform/orcas/sprites.ts
import json, os, shutil, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import extreme, feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
NEW_DOT = ["dot_scuba"]
REUSED_DOT = ["dot_lookup", "dot_aha", "dot_shrug", "dot_scratch", "dot_magnify", "dot_droop", "dot_two", "dot_three", "dot_surprised"]
OWN = ["orca", "blue_whale", "shark", "seal", "salmon", "dolphin", "elephant", "sailboat"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(px[:, :, 3]), "feet": feet(px[:, :, 3]), "ball": red_ball(px)}


for n in NEW_DOT:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dot", n + ".png"))
    out[n] = dot_entry(n, im)
    shutil.copy(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "images", "dot", n + ".png"))
for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))
out["dot_magnify"]["head"] = [396, 711, 287.0]  # the lens overlaps the head (dwarf-planet-ed138/qa/measure.png)
# the scuba pose floats: its head disc catches the mask + head, which is what we want for sizing

for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "orcas", n + ".png"))
    a = np.array(im)[:, :, 3] > 128
    ys, xs = np.where(a)
    out[n] = {"src": f"orcas/{n}.png", "w": im.width, "h": im.height,
              "centre": [float(xs.mean()), float(ys.mean())], "nose": extreme(a, "right") if n in ("orca", "shark", "dolphin") else extreme(a, "left")}
    if n == "elephant":
        out[n]["feet"] = feet(np.array(im)[:, :, 3])
# the boat's rudder: the lowest opaque point in the right third of the picture
sb = np.array(Image.open(os.path.join(ROOT, "public", "orcas", "sailboat.png")))[:, :, 3] > 128
h, w = sb.shape
right = np.zeros_like(sb); right[:, int(w * 0.6):] = sb[:, int(w * 0.6):]
out["sailboat"]["rudder"] = extreme(right, "bottom")
# waterline: the widest hull row (the stripe band sits just above it)
rows = sb.sum(1)
out["sailboat"]["deck"] = float(int(np.argmax(rows)))

ts = "// generated by images/orcas/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "longform", "orcas", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk not in ("src", "ball")} for k, v in out.items() if not k.startswith("dot_") or k == "dot_scuba"}))
