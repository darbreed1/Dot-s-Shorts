# timeline.py - lay the 10 voice sections end to end (START, then GAP between sections), map every script word onto
# its voice time (images/lib/captions.py per section), and write src/longform/orcas/timeline.ts + out/orcas-longform.srt
import json, os, re, subprocess, sys, wave

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
START, GAP, TAIL = 0.4, 1.1, 1.6
TITLES = ["Zero", "Meet the orca", "Top predator", "Close calls", "Clue 1: family food rules",
          "Clue 2: we sound strange", "Clue 3: a careful brain", "What captivity changes", "Putting the clues together",
          "Every chance"]

secs, words, srt, at = [], [], [], START
tmp = os.path.join(HERE, "tmp")
os.makedirs(tmp, exist_ok=True)
for i in range(1, 11):
    n = f"{i:02d}"
    with wave.open(os.path.join(ROOT, "public", "orcas", "vo", f"s{n}.wav")) as f:
        dur = f.getnframes() / f.getframerate()
    subprocess.run([sys.executable, os.path.join(ROOT, "images", "lib", "captions.py"), os.path.join(HERE, "script", f"s{n}.txt"),
                    os.path.join(HERE, "words", f"s{n}.json"), str(at), os.path.join(tmp, f"s{n}.ts"), os.path.join(tmp, f"s{n}.srt")],
                   check=True, capture_output=True)
    src = open(os.path.join(tmp, f"s{n}.ts")).read()
    words += json.loads(src[src.index("["):src.rindex("]") + 1])
    srt.append(open(os.path.join(tmp, f"s{n}.srt")).read().strip())
    secs.append({"n": i, "at": round(at, 3), "dur": round(dur, 3), "title": TITLES[i - 1]})
    at += dur + GAP
end = round(secs[-1]["at"] + secs[-1]["dur"] + TAIL, 2)

# renumber the srt cues across sections
cues, k = [], 1
for block in "\n\n".join(srt).split("\n\n"):
    lines = block.strip().split("\n")
    if len(lines) >= 3:
        cues.append("\n".join([str(k)] + lines[1:]))
        k += 1
open(os.path.join(ROOT, "out", "orcas-longform.srt"), "w").write("\n\n".join(cues) + "\n")
ts = "// generated by images/orcas/timeline.py - do not edit\n"
ts += "export const SECTIONS = " + json.dumps(secs, indent=1) + " as const;\n"
ts += f"export const END = {end};\n"
ts += "export const WORDS = " + json.dumps(words) + " as const;\n"
open(os.path.join(ROOT, "src", "longform", "orcas", "timeline.ts"), "w").write(ts)
for s in secs:
    m, sec = divmod(int(s["at"]), 60)
    print(f'{m}:{sec:02d}  s{s["n"]:02d} {s["title"]:32s} dur {s["dur"]:.2f}')
print("end", end, f"= {int(end // 60)}:{int(end % 60):02d}", len(words), "words", k - 1, "cues")
