# prep.py - trim, measure and pre-blur dwarf-planet-ed138 sprites; writes public/ PNGs + src/shorts/dwarf-planet-ed138/sprites.ts
import json, os, shutil, sys
import cv2
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "images", "lib"))
from cutout import blur_copy, feet, inscribed_disc, red_ball, trim  # noqa: E402

RAW = os.path.join(HERE, "raw")
NEW_DOT = ["dot_magnify", "dot_scratch"]
REUSED_DOT = ["dot_lookup", "dot_shrug", "dot_watch"]  # already trimmed in public/dot by earlier episodes
OWN = ["pluto", "ed138", "observatory"]

out = {}


def dot_entry(n, im):
    px = np.array(im)
    a = px[:, :, 3]
    return {"src": f"dot/{n}.png", "w": im.width, "h": im.height, "head": inscribed_disc(a), "feet": feet(a), "ball": red_ball(px)}


for n in NEW_DOT:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dot", n + ".png"))
    out[n] = dot_entry(n, im)
    shutil.copy(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "images", "dot", n + ".png"))
for n in REUSED_DOT:
    out[n] = dot_entry(n, Image.open(os.path.join(ROOT, "public", "dot", n + ".png")).convert("RGBA"))

# magnifier: the lens overlaps the head, so the head disc swallows it; head + lens read off qa/measure.png
# (head: left edge + bottom of the face, radius as in the other poses; lens: the grey ring)
out["dot_magnify"]["head"] = [396, 711, 287.0]
out["dot_magnify"]["lens"] = [639, 666, 160.0]

ims = {}
for n in OWN:
    im, _ = trim(os.path.join(RAW, n + ".png"), os.path.join(ROOT, "public", "dwarf-planet-ed138", n + ".png"))
    ims[n] = np.array(im)
    out[n] = {"src": f"dwarf-planet-ed138/{n}.png", "w": im.width, "h": im.height}

# planets: the ball = largest inscribed disc of the silhouette (outline included, so r reaches the outer edge
# minus a little); the outline-outer radius is the alpha extent
for n in ["pluto", "ed138"]:
    a = ims[n][:, :, 3]
    out[n]["disc"] = inscribed_disc(a)
    ys, xs = np.where(a > 128)
    out[n]["outer"] = [float((xs.min() + xs.max()) / 2), float((ys.min() + ys.max()) / 2), float((xs.max() - xs.min()) / 2)]

# observatory: dome centre + radius read off qa/measure.png (the white-blob search caught one half of the slit)
a = ims["observatory"][:, :, 3]
out["observatory"]["dome"] = [1062.0, 110.0, 135.0]
ys, xs = np.where(a > 128)
out["observatory"]["base"] = float(ys.max())
out["observatory"]["top"] = float(ys.min())

# depth of field copies for Dot's medium shots (the mountain behind him) and the sky balls
blur_copy(Image.fromarray(ims["observatory"]), os.path.join(ROOT, "public", "dwarf-planet-ed138", "observatory_blur.png"), 3.0)
out["observatory"]["blur"] = "dwarf-planet-ed138/observatory_blur.png"

ts = "// generated by images/dwarf-planet-ed138/prep.py - do not edit\n"
ts += "export const S = " + json.dumps(out, indent=1) + " as const;\n"
open(os.path.join(ROOT, "src", "shorts", "dwarf-planet-ed138", "sprites.ts"), "w").write(ts)
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk not in ("src",)} for k, v in out.items()}))
